def save_plants_to_json(plants: List[Plant], output_path: str):
    """保存植物数据到JSON文件"""
    
    # 去重（基于ID和拉丁学名）
    seen_ids = set()
    seen_latins = set()
    unique_plants = []
    
    for plant in plants:
        if plant.id not in seen_ids and plant.name_latin not in seen_latins:
            seen_ids.add(plant.id)
            seen_latins.add(plant.name_latin)
            unique_plants.append(plant)
    
    # 转换为字典
    plants_dict = [asdict(plant) for plant in unique_plants]
    
    # 收集统计信息
    families = set()
    zones = set()
    protected_count = 0
    
    for plant in unique_plants:
        if plant.family:
            families.add(plant.family)
        if plant.garden_zones:
            for zone in plant.garden_zones:
                zones.add(zone)
        if plant.protection_status and plant.protection_status.strip():
            protected_count += 1
    
    # 创建元数据
    metadata = {
        "source": "北京植物园扩展植物数据库",
        "description": "北京植物园植物数据库（扩展版，200+种）",
        "total_count": len(unique_plants),
        "family_count": len(families),
        "zone_count": len(zones),
        "protected_count": protected_count,
        "collected_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "version": "3.0"
    }
    
    # 完整版本
    full_data = {
        "metadata": metadata,
        "plants": plants_dict
    }
    
    # 简化版本
    compact_data = {
        "metadata": {
            "total": len(unique_plants),
            "updated": datetime.now().strftime("%Y-%m-%d")
        },
        "plants": plants_dict
    }
    
    # 保存完整版本
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(full_data, f, ensure_ascii=False, indent=2)
    
    # 保存压缩版本
    compact_path = output_path.replace('.json', '.min.json')
    with open(compact_path, 'w', encoding='utf-8') as f:
        json.dump(compact_data, f, ensure_ascii=False, separators=(',', ':'))
    
    print(f"数据已保存到: {output_path}")
    print(f"压缩版已保存到: {compact_path}")
    print(f"共 {len(unique_plants)} 种植物")
    print(f"包含 {len(families)} 个科，{len(zones)} 个园区")
    print(f"其中 {protected_count} 种为保护植物")
    
    return unique_plants

